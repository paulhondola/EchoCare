"""Ecou's faces and text for the 8x13 LED matrix (08-ecou.md §2.5).

Drawn as text so they are easy to edit: '#' is full brightness, '+' is dim, '.' is off.
The sketch runs the matrix with brightness 0..7.
"""

import numpy as np

ROWS, COLS = 8, 13
_LEVEL = {".": 0, "+": 2, "#": 7}


def _parse(art: str) -> np.ndarray:
    lines = [line.strip() for line in art.strip().splitlines()]
    assert len(lines) == ROWS and all(len(line) == COLS for line in lines), art
    return np.array([[_LEVEL[c] for c in line] for line in lines], dtype=np.uint8)


