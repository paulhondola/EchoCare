# 5x7 glyphs, only what Ecou says: „BINE?” and digits for a countdown.
_GLYPHS = {
    "B": ["####.", "#...#", "#...#", "####.", "#...#", "#...#", "####."],
    "I": ["###", ".#.", ".#.", ".#.", ".#.", ".#.", "###"],
    "N": ["#...#", "##..#", "#.#.#", "#.#.#", "#..##", "#...#", "#...#"],
    "E": ["#####", "#....", "#....", "####.", "#....", "#....", "#####"],
    "?": [".###.", "#...#", "....#", "...#.", "..#..", ".....", "..#.."],
    " ": ["...", "...", "...", "...", "...", "...", "..."],
}


def text_strip(text: str) -> np.ndarray:
    """The text as one wide image, with a blank screen before and after it."""
    columns = [np.zeros((ROWS, COLS), dtype=np.uint8)]
    for ch in text.upper():
        glyph = _GLYPHS[ch]
        art = np.array([[7 if c == "#" else 0 for c in row] for row in glyph], dtype=np.uint8)
        padded = np.zeros((ROWS, art.shape[1] + 1), dtype=np.uint8)
        padded[0:7, 0 : art.shape[1]] = art
        columns.append(padded)
    columns.append(np.zeros((ROWS, COLS), dtype=np.uint8))
    return np.hstack(columns)


def scroll_frames(text: str):
    """Successive 8x13 windows over the text, one column apart."""
    strip = text_strip(text)
    for x in range(strip.shape[1] - COLS + 1):
        yield strip[:, x : x + COLS]
